"""Restricted loading for locally generated PyG graph datasets."""

from __future__ import annotations

import inspect
from pathlib import Path
from typing import Any

import torch
from torch_geometric.data import Data
from torch_geometric.data.data import DataEdgeAttr, DataTensorAttr
from torch_geometric.data.storage import (
    BaseStorage,
    EdgeStorage,
    GlobalStorage,
    NodeStorage,
)


_PYG_SAFE_GLOBALS = (
    Data,
    DataEdgeAttr,
    DataTensorAttr,
    BaseStorage,
    EdgeStorage,
    GlobalStorage,
    NodeStorage,
)


def load_processed_graph_dataset(path: str | Path) -> tuple[Data, dict[str, Any]]:
    """Load a known PyG ``InMemoryDataset`` archive without unrestricted pickle.

    The processed files are generated by this project and contain a ``(Data,
    slices)`` tuple.  PyTorch's restricted loader is intentionally required;
    silently falling back to ``weights_only=False`` would turn a local cache
    into an arbitrary-code execution boundary.
    """

    try:
        load_parameters = inspect.signature(torch.load).parameters
    except (TypeError, ValueError) as exc:
        raise RuntimeError("Restricted PyTorch dataset loading is unavailable") from exc
    if "weights_only" not in load_parameters:
        raise RuntimeError("PyTorch weights_only loading is required for graph datasets")

    try:
        safe_globals = torch.serialization.safe_globals
    except AttributeError as exc:
        raise RuntimeError("PyTorch safe globals are unavailable for graph datasets") from exc

    with safe_globals(list(_PYG_SAFE_GLOBALS)):
        payload = torch.load(path, map_location="cpu", weights_only=True)

    if not isinstance(payload, tuple) or len(payload) not in (2, 3):
        raise ValueError("Invalid processed graph dataset envelope")

    data, slices = payload[:2]
    if isinstance(data, dict):
        data = Data.from_dict(data)
    if not isinstance(data, Data) or not isinstance(slices, dict):
        raise ValueError("Processed graph dataset contains an invalid PyG payload")
    return data, slices
