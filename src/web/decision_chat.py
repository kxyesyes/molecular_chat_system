"""Opt-in transport bridge; no routing, planning, model fallback or global state."""
import asyncio
import json
import math
from contextlib import suppress

from src.agent.contracts import AgentResult, AgentExecutionError, AgentErrorCode, RunOutcome
from src.agent.persistence.redaction import redact_sensitive, sanitize_bounded
from src.agent.runtime.event_bus import AgentEventBus


def _finite_display(value):
    """Display-only replacement; non-finite diagnostics are never JSON numbers."""
    if isinstance(value, dict):
        return {k: _finite_display(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_finite_display(v) for v in value]
    if type(value) is float and not math.isfinite(value):
        return '[non-finite value omitted]'
    return value


async def process_decision_message(handler, websocket, *, context, decision_loop,
                                   request_kind, allowed_tools, required_tools,
                                   requirements=None, continuation_id=None, clarified_query=None):
    """Caller owns identity, trace and permissions; never forward browser kwargs.

    Each request has its own event queue. Scientific final text is rendered by
    the harness, not regenerated by the chat model. Disconnection does not replay
    or resume tools; the harness owns cancellation and uncertain tool state.
    """
    if not context.user_id or not context.session_id:
        raise ValueError('Server-bound user and session are required')
    loop = asyncio.get_running_loop()
    queue = asyncio.Queue()

    def on_event(event):
        loop.call_soon_threadsafe(queue.put_nowait, event.to_dict())

    async def run():
        try:
            return await decision_loop.run(context, request_kind=request_kind,
                allowed_tools=allowed_tools, required_tools=required_tools,
                requirements=requirements, continuation_id=continuation_id,
                clarified_query=clarified_query,
                event_bus=AgentEventBus(on_event=on_event, state_store=decision_loop.store))
        except Exception:
            # Never include provider exception text, URLs, credentials or traceback.
            return AgentResult(context.trace_id, False, '代理执行未完成，请检查模型或服务状态。',
                error=AgentExecutionError(AgentErrorCode.INTERNAL_ERROR, 'Isolated agent execution failed'),
                outcome=RunOutcome.FAILED)
        finally:
            # Schedule after all previously queued callbacks, including worker events.
            loop.call_soon(queue.put_nowait, None)

    task = asyncio.create_task(run())
    event_display_changed = False
    try:
        while True:
            event = await queue.get()
            if event is None:
                break
            public_event = _finite_display(handler._sanitize_agent_event(event))
            event_changed = public_event != event
            event_display_changed |= event_changed
            await websocket.send_text(json.dumps({'type': 'agent_event', 'event': public_event,
                'display_redacted_or_truncated': event_changed}, ensure_ascii=False, allow_nan=False))
        result = await task
    finally:
        if not task.done():
            task.cancel()
        with suppress(asyncio.CancelledError):
            await task

    envelope = result.to_legacy_dict()
    status = 'waiting_for_input' if result.metadata.get('waiting_for_input') else envelope['status']
    envelope.update(type='agent_result', trace_id=result.trace_id, status=status)
    envelope['final_answer'] = result.final_answer or result.message
    # Existing bounded privacy primitives; explicitly flag any changed display.
    keyed = handler._sanitize_agent_event_keys(envelope, max_depth=16, max_items=256)
    bounded, changed = sanitize_bounded(keyed, max_depth=16,
                                       max_items=256, max_text_chars=16384)
    public = _finite_display(redact_sensitive(bounded))
    changed = changed or keyed != envelope or public != bounded or event_display_changed
    public['display_redacted_or_truncated'] = changed
    if changed:
        public.setdefault('warnings', []).append('部分显示内容已脱敏或省略，请查阅授权证据记录。')
    await websocket.send_text(json.dumps(public, ensure_ascii=False, allow_nan=False))
    await websocket.send_text(json.dumps({
        'type': 'complete', 'content': public['final_answer'], 'trace_id': public['trace_id'],
        'status': status, 'continuation_id': public['metadata'].get('continuation_id'),
        'display_redacted_or_truncated': changed,
    }, ensure_ascii=False, allow_nan=False))
    return result
