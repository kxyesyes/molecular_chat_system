@pytest.mark.parametrize("shape", ["array", "object"])
@pytest.mark.parametrize("nodes", [255, 256, 257])
def test_node_boundary_counts_keys_and_precedes_model_validation(shape, nodes, monkeypatch):
    api = contract()
    if shape == "array":
        # One root list plus N-1 scalar nodes.
        value = [0] * (nodes - 1)
    else:
        # One root +127 keys +127 scalar values =255. Replacing one scalar
        # with [0] or [0,0] adds exactly one or two nodes, at depth <=2.
        value = {str(i): 0 for i in range(127)}
        if nodes > 255:
            value["0"] = [0] * (nodes - 255)
    raw = json.dumps(value)
    assert len(raw.encode("utf-8")) < 8192
    visited = observe_validation(api, monkeypatch)
    reject_raw(api, raw)
    assert visited == ([True] if nodes <= 256 else [])


