def wire(data):
    return json.dumps({"proposal": data}, ensure_ascii=False, separators=(",", ":"))


def reject_raw(api, raw):
    with pytest.raises(DecisionProtocolError) as caught:
        api.parse_docking_preparation_json(raw)
    error = caught.value
    assert error.code == ERROR
    assert error.args == (ERROR,)
    assert error.schema_issues == []
    assert error.__cause__ is None
    rendered = "".join(traceback.format_exception(type(error), error, error.__traceback__))
    public = str(error) + repr(error) + repr(vars(error)) + rendered
    assert "private-value-marker" not in public


def reject_proposal(api, data):
    reject_raw(api, wire(data))
    with pytest.raises(ValidationError):
        api.DockingPreparationProposal(**data)
    with pytest.raises(ValidationError):
        api.DockingPreparationEnvelope(proposal=data)


def observe_validation(api, monkeypatch):
    """Keep real validation; positive control proves the observation is live."""
    visited = []
    original = api.DockingPreparationEnvelope.model_validate

    def observe(cls, value, *args, **kwargs):
        visited.append(True)
        return original(value, *args, **kwargs)

    monkeypatch.setattr(api.DockingPreparationEnvelope, "model_validate", classmethod(observe))
    assert api.parse_docking_preparation_json(MINIMAL).kind == "docking_request"
    assert visited == [True]
    visited.clear()
    return visited


