FIRST = '对 CCO 做反向寻靶，列出前五个候选靶点、物种、相似度及局限。'
FOLLOWUP = '查找排名第一的靶点结构，并说明能否继续对接。'


class NoModel:
    async def generate(self, *args, **kwargs):
        pytest.fail('ranked scientific presentation must not be generated by a model')


class Socket:
    def __init__(self):
        self.scope, self.messages = {}, []

    async def send_text(self, value):
        self.messages.append(json.loads(value))


def make_handler(case, *, summarize=False):
    agent = SupervisorAgent(tools={case.tool.name: case.tool},
        harness_factory=HarnessFactory(mode='legacy'), state_store=case.store)
    return ChatHandler(NoModel(), None, agent,
        {'agent': {'summarize_workflow_results': summarize}, 'inference': {'stream': False}})


def turn(handler, message, history, session='owner-session'):
    socket = Socket()
    asyncio.run(handler._process_message(socket, message, enable_rag=False, enable_tools=True,
        conversation_history=history, session_id=session))
    completed = [frame for frame in socket.messages if frame['type'] == 'complete']
    assert completed, socket.messages
    return completed[-1], socket.messages


@pytest.mark.parametrize('summarize', [False, True])
def test_chat_captures_owned_current_rank_and_shows_only_requested_five(ranked, summarize):
    handler = make_handler(ranked, summarize=summarize)
    history = []
    result, frames = turn(handler, FIRST, history)
    context = history[-1].get('reverse_target_evidence')
    assert context and context['session_id'] == 'owner-session'
    answer = result['content']
    assert '前 5' in answer and '完整证据保留 10' in answer
    assert 'Synthetic E' in answer and 'Synthetic F' not in answer
    assert '非实验' in answer and 'Morgan/MACCS' in answer
    from src.web.reverse_target_followup import RankedReverseEvidence
    saved = RankedReverseEvidence(ranked.store, ranked.tool)
    assert saved.resolve(context, session_id='owner-session', rank=10)['record']['target_name'] == 'Synthetic J'
    with ranked.store._connect() as connection:
        payload = connection.execute('SELECT output_json FROM agent_checkpoints WHERE id=?',
            (context['observation_id'],)).fetchone()[0]
    assert len(json.loads(payload)['data']) == 10


