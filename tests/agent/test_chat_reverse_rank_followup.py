@pytest.mark.parametrize('early_return', ['temperature', 'input_budget', 'allocation_busy', 'tools_disabled'])
def test_early_return_at_admission_consumes_old_rank_pointer(ranked, monkeypatch, early_return):
    from src.web.chat_handler import MAX_RETAINED_ALLOCATIONS
    handler, history = make_handler(ranked), []
    turn(handler, FIRST, history)
    options = dict(enable_rag=False, enable_tools=True, conversation_history=history, session_id='owner-session')
    query = '你好'
    if early_return == 'temperature': options['temperature'] = float('nan')
    elif early_return == 'input_budget': query = 'x' * (handler._input_limit() + 1)
    elif early_return == 'allocation_busy': handler._allocation_tasks.update(object() for _ in range(MAX_RETAINED_ALLOCATIONS))
    else:
        query, options['enable_tools'] = FOLLOWUP, False
    asyncio.run(handler._process_message(Socket(), query, **options))
    handler._allocation_tasks.clear()
    import src.web.ranked_target_structures as module
    monkeypatch.setattr(module, 'BoundedJsonClient', lambda: pytest.fail('early return must revoke old rank'))
    result, _ = turn(handler, FOLLOWUP, history)
    assert '排名证据不可用' in result['content']


@pytest.mark.parametrize('close_fails', [False, True])
def test_owned_transport_cleanup_never_leaks_through_websocket_or_logs(ranked, monkeypatch, caplog, close_fails):
    import requests
    from fastapi import WebSocketDisconnect

    marker = 'SYNTHETIC_PRIVATE_QUERY_MARKER'
    providers, calls, closes = Http(), [], []
    original_close = requests.Session.close

    def request(session, method, url, **kwargs):
        calls.append(url)
        if 'uniprot.org' in url:
            payload = {'results': providers.records}
        elif 'graphql' in url:
            payload = {'data': {'entries': [providers.entry]}}
        else:
            assert 'search.rcsb.org' in url
            payload = {'total_count': 1, 'result_set': [{'identifier': '1ABC_1'}]}
        response = requests.Response()
        response.status_code = 200
        response.url = url
        response._content = json.dumps(payload).encode('utf-8')
        response._content_consumed = True
        response.headers['Content-Type'] = 'application/json'
        return response

    def close(session):
        original_close(session)
        closes.append(True)
        if close_fails:
            raise OSError(marker)

    monkeypatch.setattr(requests.Session, 'request', request)
    monkeypatch.setattr(requests.Session, 'close', close)
    monkeypatch.setattr(requests.adapters.HTTPAdapter, 'send',
        lambda *a, **kw: pytest.fail('no external network in this regression'))

    class SessionSocket(Socket):
        def __init__(self):
            super().__init__()
            self.scope['agent_session_id'] = 'owner-session'
            self.queries = iter([FIRST, FOLLOWUP, FOLLOWUP] if close_fails else [FIRST, FOLLOWUP])

        async def accept(self):
            pass

        async def receive_text(self):
            query = next(self.queries, None)
            if query is None:
                raise WebSocketDisconnect()
            return json.dumps({'message': query, 'enable_rag': False, 'enable_tools': True})

    socket = SessionSocket()
    asyncio.run(make_handler(ranked).handle_websocket(socket))
    assert marker not in json.dumps(socket.messages) and marker not in caplog.text
    assert len(calls) == 4 and closes == [True]
    completed = [frame for frame in socket.messages if frame['type'] == 'complete']
    if close_fails:
        assert len(completed) == 3
        assert completed[1]['status'] == 'partial' and '1ABC' not in completed[1]['content']
        assert completed[2]['status'] == 'partial' and '排名证据不可用' in completed[2]['content']
    else:
        assert len(completed) == 2
        assert completed[1]['status'] == 'succeeded' and '1ABC' in completed[1]['content']
