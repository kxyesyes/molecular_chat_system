def test_foreign_run_owner_prevents_capture_even_when_live_result_matches(ranked, monkeypatch):
    handler = make_handler(ranked)
    original = handler._execute_agent
    async def changed(*args, **kwargs):
        result = await original(*args, **kwargs)
        with ranked.store._connect() as connection:
            connection.execute('UPDATE agent_runs SET session_id=? WHERE trace_id=?',
                ('foreign', result['trace_id']))
        return result
    monkeypatch.setattr(handler, '_execute_agent', changed)
    history = []
    result, _ = turn(handler, FIRST, history)
    assert not history[-1].get('reverse_target_evidence')
    assert '排名证据不可用' in result['content']


def test_first_rank_followup_uses_provider_and_cannot_invoke_docking(ranked, monkeypatch):
    handler, history = make_handler(ranked), []
    turn(handler, FIRST, history)
    import src.web.ranked_target_structures as module
    http = Http()
    monkeypatch.setattr(module, 'BoundedJsonClient', lambda: http)
    def never(*args, **kwargs):
        pytest.fail('rank continuation must not dispatch scientific workflow or rerun reverse')
    monkeypatch.setattr(handler, '_execute_agent', never)
    monkeypatch.setattr(ranked.producer, 'predict_with_receipt', never)
    result, frames = turn(handler, FOLLOWUP, history)
    answer = result['content']
    assert all(text in answer for text in ['Synthetic A', 'Homo sapiens', 'P12345', '1ABC', '未启动', '口袋'])
    assert 'https://www.rcsb.org/structure/1ABC' in answer
    assert '| RCSB PDB /' in answer
    assert 'RCSB&#95;PDB' not in answer
    assert 'entry version' in answer and '17' in answer
    assert http.closed == 1
    assert history[-1].get('reverse_target_evidence')
    assert not any(frame['type'] == 'docking_consent' for frame in frames)


@pytest.mark.parametrize('mode', ['fresh', 'foreign', 'prose_only', 'intervening', 'retired', 'changed_pointer'])
def test_rank_followup_requires_last_current_owned_evidence(ranked, monkeypatch, mode):
    handler, history = make_handler(ranked), []
    turn(handler, FIRST, history)
    if mode == 'fresh': history = []
    elif mode == 'prose_only': history = [{'user': FIRST, 'assistant': '第一名为 P12345'}]
    elif mode == 'intervening': history.append({'user': '你好', 'assistant': '你好'})
    elif mode == 'retired': ranked.producer.close_strict()
    elif mode == 'changed_pointer': history[-1]['reverse_target_evidence']['trace_id'] = 'rank-trace'
    def never(*args, **kwargs):
        pytest.fail('invalid rank context must not invoke providers, workflow or model')
    import src.web.ranked_target_structures as module
    monkeypatch.setattr(module, 'BoundedJsonClient', never)
    monkeypatch.setattr(handler, '_execute_agent', never)
    result, _ = turn(handler, FOLLOWUP, history, 'foreign' if mode == 'foreign' else 'owner-session')
    assert '排名证据' in result['content'] and 'P12345' not in result['content']
    assert not history[-1].get('reverse_target_evidence')


